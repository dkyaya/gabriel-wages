def expansion_eligibility(row: dict[str, Any]) -> tuple[str, list[str]]:
    status = row["primary_terminal_status"]
    if status not in SUCCESS: return "extraction_repair_needed" if status in {"parse_timeout", "parse_error", "extraction_error"} else "not_processible", []
    kind = row["detected_file_type"]
    tables = int(row.get("table_count", 0) or 0); structured = int(row.get("structured_record_count", 0) or 0); chars = int(row.get("character_count", 0) or 0)
    if kind == "csv": eligibility = "direct_structured_processing_ready"
    elif kind == "html" and (tables or structured) and chars: eligibility = "mixed_structured_and_text_processing_ready"
    elif kind == "html" and (tables or structured): eligibility = "direct_structured_processing_ready"
    elif status == "extracted_low_yield_usable": eligibility = "low_yield_context_only"
    else: eligibility = "deterministic_text_pattern_processing_ready"
    families = [value for value in split_values(row.get("source_family", "")) if value in ALLOWED_FAMILIES]
    if not families:
        families = [value for value in split_values(row.get("secondary_source_families", "")) if value in ALLOWED_FAMILIES]
    if eligibility == "low_yield_context_only" and not families: families = ["narrative_mechanism_context"]
    if not families: families = ["unclear"]
    return eligibility, sorted(set(families))


