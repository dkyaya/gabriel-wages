def normalized_text(value: str) -> str:
    return value.replace("\x00", "").replace("\r\n", "\n").replace("\r", "\n")


def decode_bytes(data: bytes) -> tuple[str, str, list[str]]:
    warnings_out: list[str] = []
    if data.startswith(b"\xef\xbb\xbf"):
        return data.decode("utf-8-sig", errors="replace"), "utf-8-sig", warnings_out
    try:
        return data.decode("utf-8"), "utf-8", warnings_out
    except UnicodeDecodeError:
        match = from_bytes(data).best()
        if match is not None:
            encoding = match.encoding or "unknown"
            warnings_out.append("non_utf8_decoded")
            return str(match), encoding, warnings_out
        warnings_out.append("replacement_decode")
        return data.decode("utf-8", errors="replace"), "utf-8-replacement", warnings_out


class DeterministicGzipWriter:
    def __init__(self, path: Path):
        self.path = path
        self.temporary = path.with_name(path.name + f".{os.getpid()}.tmp")
        self.raw: io.BufferedWriter | None = None
        self.gzip: gzip.GzipFile | None = None

    def __enter__(self) -> gzip.GzipFile:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.raw = self.temporary.open("wb")
        self.gzip = gzip.GzipFile(filename="", mode="wb", fileobj=self.raw, compresslevel=6, mtime=0)
        return self.gzip

    def __exit__(self, exc_type: Any, exc: Any, traceback: Any) -> None:
        try:
            if self.gzip:
                self.gzip.close()
            if self.raw:
                self.raw.close()
            if exc_type is None:
                os.replace(self.temporary, self.path)
            else:
                self.temporary.unlink(missing_ok=True)
        finally:
            self.temporary.unlink(missing_ok=True)


