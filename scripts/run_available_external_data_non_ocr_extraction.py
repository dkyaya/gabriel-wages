def extract_one_os_bounded(row: dict[str, Any]) -> tuple[dict[str, Any], list[dict[str, Any]], list[dict[str, Any]], list[str]]:
    """Put large libxml work behind an enforceable process boundary.

    Python alarms cannot interrupt every libxml C call. Small payloads stay in
    process; HTML payloads at least 8 MiB run in a short-lived child so the
    configured timeout is an actual wall-clock bound.
    """
    if row["detected_file_type"] != "html" or int(row["byte_size"]) < 8 * 1024**2:
        return extract_one(row)
    request = TMP / f"bounded_{row['canonical_payload_id']}_{os.getpid()}.request.json"
    response = TMP / f"bounded_{row['canonical_payload_id']}_{os.getpid()}.response.json"
    atomic_json(request, row)
    remove_payload_artifacts(row)
    try:
        subprocess.run([sys.executable, str(Path(__file__).resolve()), "extract-single", "--row-json", str(request), "--result-json", str(response)], cwd=core.ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=PER_PAYLOAD_TIMEOUT + 5, check=True)
        payload = read_json(response)
        return payload["result"], payload["artifacts"], payload["indexes"], payload["warnings"]
    except subprocess.TimeoutExpired:
        remove_payload_artifacts(row)
        return timeout_result(row, "html_child_process_wall_timeout")
    except (subprocess.CalledProcessError, FileNotFoundError, json.JSONDecodeError) as exc:
        remove_payload_artifacts(row)
        result, artifacts, indexes, warnings_out = timeout_result(row, f"html_child_process_error:{type(exc).__name__}")
        result["primary_terminal_status"] = "parse_error"
        result["modality_status"] = "html_parse_error"
        return result, artifacts, indexes, warnings_out
    finally:
        request.unlink(missing_ok=True); response.unlink(missing_ok=True)


def smoke(rows: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    rows = rows or [locked_row(row) for row in load_ready_rows()]
    samples = sample_rows(rows)
    results = []
    source_bytes = output_bytes = 0
    for row in samples:
        result, artifacts, indexes, warnings_out = extract_one(row, smoke=True)
        results.append({"canonical_payload_id": row["canonical_payload_id"], "readiness_status": row["readiness_status"], "detected_file_type": row["detected_file_type"], "source_bytes": int(row["byte_size"]), "terminal_status": result["primary_terminal_status"], "modality_status": result["modality_status"], "artifact_bytes": result["artifact_bytes"], "character_count": result["character_count"], "page_count": result["page_count"], "table_count": result["table_count"], "structured_record_count": result["structured_record_count"], "lineage_preserved": result["canonical_payload_id"] == row["canonical_payload_id"], "warning_codes": warnings_out})
        source_bytes += int(row["byte_size"]); output_bytes += int(result["artifact_bytes"])
        remove_payload_artifacts(row)
    ratios_by_type: dict[str, float] = {}
    for kind in EXPECTED_TYPES:
        source = sum(item["source_bytes"] for item in results if item["detected_file_type"] == kind)
        output = sum(item["artifact_bytes"] for item in results if item["detected_file_type"] == kind)
        ratios_by_type[kind] = output / source if source else 0.0
    projection = 0
    for kind in EXPECTED_TYPES:
        source_total = sum(int(row["byte_size"]) for row in rows if row["detected_file_type"] == kind)
        ratio = ratios_by_type[kind]
        conservative = min(1.0, max(ratio * 2.5, {"pdf": 0.04, "html": 0.15, "csv": 1.5, "txt": 1.5}.get(kind, 0.2)))
        projection += int(source_total * conservative)
    free = free_space()
    temporary_peak = max((int(row["byte_size"]) for row in rows), default=0) * 2
    report = {"passed": len(results) == 7 and all(item["terminal_status"] in TERMINAL for item in results) and free - projection - temporary_peak >= MIN_FREE_RESERVE, "sample_count": len(results), "samples": results, "sample_source_bytes": source_bytes, "sample_compressed_output_bytes": output_bytes, "sample_compression_ratio": round(source_bytes / max(output_bytes, 1), 6), "observed_output_to_source_ratios": ratios_by_type, "conservative_projected_extraction_bytes": projection, "temporary_peak_bytes": temporary_peak, "free_bytes_before_production": free, "reserve_bytes": MIN_FREE_RESERVE, "projected_free_bytes_after_extraction": free - projection - temporary_peak, "no_ocr": True, "no_network": True, "full_smoke_artifacts_cleaned": all(not p.exists() for row in samples for p in extraction_paths(row).values()), "completed_at": utc_now()}
    atomic_json(OUTPUT / "extraction_smoke_results.json", report)
    return report


def preflight() -> None:
    if current_head() != REQUIRED_COMMIT and not is_ancestor(REQUIRED_COMMIT): raise RuntimeError("required readiness commit is not an ancestor")
    dirty = subprocess.check_output(["git", "status", "--short"], cwd=core.ROOT, text=True).splitlines()
    unrelated = [line for line in dirty if line != "?? scripts/run_available_external_data_non_ocr_extraction.py"]
    if unrelated: raise RuntimeError("dirty worktree preflight blocker:\n" + "\n".join(unrelated))
    if not INPUT.is_dir(): raise RuntimeError("readiness input directory missing")
    if OUTPUT.exists() and any(OUTPUT.iterdir()): raise RuntimeError("extraction output exists; resume rather than rebuild")
    matches = process_matches()
    if matches: raise RuntimeError(f"stale extraction processes: {matches}")
    if subprocess.check_output(["git", "diff", "--cached", "--name-only"], cwd=core.ROOT, text=True).strip(): raise RuntimeError("Git index must be empty")
    for root in (RETAINED, EXTRACTED, STRUCTURED, TMP):
        root.mkdir(parents=True, exist_ok=True)
        if not git_ignored(root): raise RuntimeError(f"local artifact root not ignored: {root}")
    summary = read_json(INPUT / "external_data_readiness_summary.json")
    status_summary = read_json(INPUT / "readiness_status_summary.json")["physical_payload_counts"]
    if summary["extraction_ready_unique_payloads"] != EXPECTED_TOTAL or summary["extraction_ready_bytes"] != EXPECTED_BYTES: raise RuntimeError("readiness summary mismatch")
