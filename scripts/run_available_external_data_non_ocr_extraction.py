def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=("preflight", "smoke", "run-lane", "extract-single", "finalize", "validate", "staged-audit", "build-relay"))
    parser.add_argument("--lane", type=int); parser.add_argument("--start-delay-seconds", type=int, default=0); parser.add_argument("--commit-hash", default=""); parser.add_argument("--push-status", default="not_pushed"); parser.add_argument("--row-json"); parser.add_argument("--result-json")
    args = parser.parse_args()
    if args.mode == "preflight": preflight()
    elif args.mode == "smoke": print(json.dumps(smoke(), indent=2))
    elif args.mode == "run-lane":
        if args.lane not in range(1, 6): raise RuntimeError("--lane 1..5 required")
        run_lane(args.lane, args.start_delay_seconds)
    elif args.mode == "extract-single":
        if not args.row_json or not args.result_json: raise RuntimeError("--row-json and --result-json required")
        row = read_json(Path(args.row_json))
        result, artifacts, indexes, warnings_out = extract_one(row)
        atomic_json(Path(args.result_json), {"result": result, "artifacts": artifacts, "indexes": indexes, "warnings": warnings_out})
    elif args.mode == "finalize": finalize()
    elif args.mode == "validate": validate()
    elif args.mode == "staged-audit": staged_audit()
    elif args.mode == "build-relay": build_relay(args.commit_hash, args.push_status)
    return 0


