    paths = extraction_paths(row)
    extraction_id = stable("EXTEXTRACT", row["canonical_payload_id"], row["SHA_256"], "csv_structured", EXTRACTOR_VERSION, CONFIG_VERSION)
    warnings_out: list[str] = []
