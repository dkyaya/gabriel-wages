def staged_audit() -> None:
    staged = subprocess.check_output(["git", "diff", "--cached", "--name-only"], cwd=core.ROOT, text=True).splitlines()
    # Include the audit products themselves in the prospective staged scope.
    # They are written by this command and staged immediately afterward.
    staged.extend(
        str((OUTPUT / name).relative_to(core.ROOT))
        for name in (
            "staged_file_audit.json",
            "extraction_staged_file_audit.json",
            "large_file_audit.json",
            "extraction_large_file_audit.json",
        )
    )
    staged = sorted(set(staged))
    forbidden_suffixes = {".pdf", ".html", ".xlsx", ".xls", ".zip", ".doc", ".docx", ".ppt", ".pptx", ".png", ".jpg", ".jpeg", ".gz", ".zst", ".parquet"}
    forbidden = []; oversized = []
    for name in staged:
        path = core.ROOT / name
        if name.startswith("artifacts/") or path.suffix.casefold() in forbidden_suffixes or any(token in name.casefold() for token in ("full_extracted", "full_structured", "page_body", "parser_cache", "temporary")): forbidden.append(name)
        if path.is_file() and path.stat().st_size > 50 * 1024**2: oversized.append({"path": name, "bytes": path.stat().st_size})
    audit = {"passed": not forbidden and not oversized, "staged_count": len(staged), "forbidden_payloads": forbidden, "oversized_files": oversized, "staged_files": staged, "audited_at": utc_now()}
    large = {"passed": not oversized, "threshold_bytes": 50 * 1024**2, "oversized_files": oversized, "audited_at": utc_now()}
    atomic_json(OUTPUT / "staged_file_audit.json", audit); atomic_json(OUTPUT / "extraction_staged_file_audit.json", audit); atomic_json(OUTPUT / "large_file_audit.json", large); atomic_json(OUTPUT / "extraction_large_file_audit.json", large)
    validation = read_json(OUTPUT / "validation_report.json"); checks = validation["checks"]
    for key in ("no_full_artifact_staged_pending", "no_retained_payload_staged_pending", "local_artifact_audit_pending", "staged_file_audit_pending", "large_file_audit_pending"): checks.pop(key, None)
    checks.update({"no_full_extraction_artifact_staged": not forbidden, "no_retained_payload_staged": not forbidden, "local_artifact_storage_audit_passed": read_json(OUTPUT / "local_artifact_storage_audit.json")["passed"], "staged_file_audit_passed": audit["passed"], "large_file_audit_passed": large["passed"]})
    validation.update({"passed": all(checks.values()), "check_count": len(checks), "failed": [key for key, value in checks.items() if not value], "validated_at": utc_now()}); atomic_json(OUTPUT / "validation_report.json", validation); core.write_md(OUTPUT / "validation_report.md", "# External-data non-OCR extraction validation\n\n" + "\n".join(f"- {'PASS' if value else 'FAIL'} — {key.replace('_', ' ')}" for key, value in checks.items()))
    if not audit["passed"] or not validation["passed"]: raise RuntimeError("staged/large/local audit failed")
    print(json.dumps(audit, indent=2))


